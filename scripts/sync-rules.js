// Copies the rules block out of the prototype page into src/rules.js.
// The block sits between //#LOGIC-START and //#LOGIC-END and uses no browser APIs,
// so the same code can run in the page, in tests, and later on a server.
// Run with: npm run sync
const fs = require('fs');
const path = require('path');

const page = fs.readFileSync(path.join(__dirname, '..', 'prototype', 'football-matchday.html'), 'utf8');
const m = page.match(/\/\/#LOGIC-START([\s\S]*?)\/\/#LOGIC-END/);
if (!m) throw new Error('Could not find the LOGIC-START / LOGIC-END markers in the prototype page.');

const exportsList = [
  'RV', 'G', 'GN', 'SQ', 'CARDS', 'fmtMoney',
  'owned', 'groupSq', 'hasSet', 'supply', 'rentFor', 'aliveCount',
  'canBuild', 'canSell', 'canMort', 'canUnmort', 'unmortCost', 'mortFee',
  'tradable', 'validTrade', 'tradeFees',
  'newLobby', 'startGame',
  'doRoll', 'doBuy', 'doPass', 'doEnd', 'doBail', 'doCard',
  'doBid', 'doFold',
  'doBuild', 'doSell', 'doMort', 'doUnmort',
  'doOffer', 'doAccept', 'doDropTrade',
];

const out = `// GENERATED by scripts/sync-rules.js from prototype/football-matchday.html. Do not edit by hand.
// Pure game rules for Football Matchday. State in, state out, no browser or network code.
'use strict';
${m[1].trim()}

module.exports = { ${exportsList.join(', ')} };
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'rules.js'), out);
console.log('Wrote src/rules.js (' + out.split('\n').length + ' lines)');
